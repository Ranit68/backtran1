import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

/**
 * Embeds public/index.html into a TypeScript module.
 *
 * The frontend used to be read from disk at runtime, which meant the file had to
 * be copied into the serverless bundle for the deployed site to have a homepage.
 * That copy was configured with an `includeFiles` glob in vercel.json, and
 * adding that glob is the one build-affecting change between the last commit
 * that deployed and every commit that has failed since. Rather than debug a
 * glob, the page is compiled into the bundle instead, so there is nothing to
 * copy and nothing that can go missing at runtime.
 *
 * The output is committed rather than produced on the Vercel build, because the
 * Vercel build does not run tsc. test/frontend-render.test.ts asserts this file
 * still matches public/index.html so the two cannot drift apart unnoticed.
 */

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const source = join(root, "public", "index.html");
const target = join(root, "src", "frontend-html.generated.ts");

const html = readFileSync(source, "utf8");
const next =
  "/**\n" +
  " * Generated by scripts/embed-frontend.mjs from public/index.html.\n" +
  " * Do not edit. Run `npm run embed-frontend` after changing the page.\n" +
  " */\n\n" +
  `export const FRONTEND_HTML = ${JSON.stringify(html)};\n`;

const current = existsSync(target) ? readFileSync(target, "utf8") : "";
if (current === next) {
  console.log("frontend-html.generated.ts already matches public/index.html");
} else {
  writeFileSync(target, next);
  console.log(`wrote src/frontend-html.generated.ts (${html.length} chars of page)`);
}
